def seed_badge_catalog(db: Session) -> int:
    """
    Seed the badge catalog with curated certification data.

    Returns the number of badges added/updated.
    """
    from app.models.badge import BadgeCatalog, BadgeSkillMapping

    count = 0

    for entry in BADGE_SEED_DATA:
        # Upsert badge catalog entry
        existing = db.query(BadgeCatalog).filter(
            BadgeCatalog.platform == entry["platform"],
            BadgeCatalog.external_id == entry["external_id"],
        ).first()

        if existing:
            # Update existing entry
            existing.name = entry["name"]
            existing.issuer = entry["issuer"]
            existing.url = entry["url"]
            existing.skills = entry["skills"]
            existing.difficulty_level = entry.get("difficulty_level")
            existing.estimated_cost_usd = entry.get("estimated_cost_usd")
            existing.estimated_hours = entry.get("estimated_hours")
            existing.renewal_months = entry.get("renewal_months")
            existing.is_active = True
            badge = existing
        else:
            badge = BadgeCatalog(
                external_id=entry["external_id"],
                name=entry["name"],
                issuer=entry["issuer"],
                platform=entry["platform"],
                url=entry["url"],
                skills=entry["skills"],
                difficulty_level=entry.get("difficulty_level"),
                estimated_cost_usd=entry.get("estimated_cost_usd"),
                estimated_hours=entry.get("estimated_hours"),
                renewal_months=entry.get("renewal_months"),
                is_active=True,
            )
            db.add(badge)
            db.flush()  # Get the ID
            count += 1

        # Upsert skill mappings (curated, confidence=1.0)
        for skill in entry["skills"]:
            skill_lower = skill.lower().strip()
            existing_mapping = db.query(BadgeSkillMapping).filter(
                BadgeSkillMapping.badge_id == badge.id,
                BadgeSkillMapping.skill_name == skill_lower,
            ).first()

            if not existing_mapping:
                mapping = BadgeSkillMapping(
                    badge_id=badge.id,
                    skill_name=skill_lower,
                    mapping_confidence=1.0,
                    source="curated",
                )
                db.add(mapping)

    db.commit()
    logger.info(f"Seeded badge catalog with {count} new badges ({len(BADGE_SEED_DATA)} total)")
    return count


